#!/usr/bin/env bash
#
# setup-gdrive-backup.sh — one-time Google Drive backup setup for SMILE (LXC 115)
#
# What this does:
#   1. checks rclone and pg_dump are present
#   2. verifies the Google Drive remote already authenticates
#   3. generates a crypt passphrase and writes rclone.conf (mode 0600)
#   4. prints the passphrase ONCE, for you to seal in an envelope
#   5. runs a test upload + integrity check
#
# What this deliberately does NOT do:
#   - store the passphrase anywhere except rclone.conf (mode 0600)
#   - show it again on any later run
#   - put it in the SMILE application, its database, or any export
#
# The passphrase is unrecoverable. Without it, every backup is permanently unreadable.
#
# Usage:  bash setup-gdrive-backup.sh [drive-remote-name]
#         default remote name is "gdrive"

set -euo pipefail

DRIVE_REMOTE="${1:-gdrive}"
CRYPT_REMOTE="${DRIVE_REMOTE}-crypt"
BACKUP_DIR="${BACKUP_DIR:-smile-backups}"
CONFIG="${RCLONE_CONFIG:-$HOME/.config/rclone/rclone.conf}"
MODE=600

say()  { printf '\n\033[1m%s\033[0m\n' "$*"; }
warn() { printf '\033[33m  ! %s\033[0m\n' "$*"; }
die()  { printf '\033[31m  x %s\033[0m\n' "$*" >&2; exit 1; }

# --- 0. refuse to run as root -----------------------------------------------
# rclone.conf is per-user; running as root would write it to /root/.config.
if [ "$(id -u)" -eq 0 ]; then
  die "Run as the smile service user, not root. Example:
     sudo -u smile bash $0 $DRIVE_REMOTE"
fi

# --- 1. prerequisites -------------------------------------------------------
say "1/5  Checking prerequisites"

command -v rclone >/dev/null 2>&1 || die "rclone not installed.
  Debian/Ubuntu:  apt-get install -y rclone
  or from https://rclone.org/downloads/"

command -v pg_dump >/dev/null 2>&1 || die "pg_dump not found. Install postgresql-client-17."

RCLONE_VERSION="$(rclone version | head -1 | grep -oE '[0-9]+\.[0-9]+' | head -1)"
printf '  rclone %s\n' "$RCLONE_VERSION"

# A crypt remote must not be created by rclone < 1.53.3: passwords generated by
# rclone config in v1.49.0-v1.53.2 are not considered secure (rclone#4783).
TOO_OLD="$(printf '1.53.3\n%s\n' "$RCLONE_VERSION" | sort -V | head -1)"
if [ "$TOO_OLD" = "1.53.3" ] && [ "$RCLONE_VERSION" != "$(printf '1.53.3\n' | sort -V | head -1)" ]; then
  die "rclone is older than 1.53.3. Upgrade before generating a passphrase."
fi
printf '  version OK\n'

# --- 2. verify the Drive remote --------------------------------------------
say "2/5  Verifying the Google Drive remote '$DRIVE_REMOTE'"

rclone listremotes 2>/dev/null | grep -qx "${DRIVE_REMOTE}:" \
  || die "Remote '$DRIVE_REMOTE' is not configured.

  Authorise it first. From a machine with a browser:

      rclone config            # Storage: drive, then follow the prompts

  Then copy the resulting token into this server's config, or re-run
  'rclone config' here if this host has a browser or you use a service account.

  NOTE: the Drive token is NOT the backup passphrase. It can be re-issued at any
  time. Only the passphrase printed in step 4 is unrecoverable."

printf '  testing access...'
if ! rclone lsd "${DRIVE_REMOTE}:" --timeout 30s >/dev/null 2>&1; then
  die "Cannot reach '$DRIVE_REMOTE:'. Re-authorise and retry."
fi
printf ' ok\n'

# --- 3. generate the passphrase --------------------------------------------
say "3/5  Generating the crypt passphrase"

# 32 random bytes, base64url, no padding. Generated by the machine rather than
# chosen by a human: high entropy, and the recovery path is a sealed envelope
# rather than someone's memory.
PASSPHRASE="$(head -c 32 /dev/urandom | base64 | tr '+/' '-_' | tr -d '=\n')"
# rclone's salt (password2). Distinct value, same generation.
SALT="$(head -c 32 /dev/urandom | base64 | tr '+/' '-_' | tr -d '=\n')"

OBSCURED_PASS="$(printf '%s' "$PASSPHRASE" | rclone obscure -)"
OBSCURED_SALT="$(printf '%s' "$SALT"      | rclone obscure -)"

# --- 4. write the config ----------------------------------------------------
say "4/5  Writing rclone.conf"

mkdir -p "$(dirname "$CONFIG")"
touch "$CONFIG"; chmod "$MODE" "$CONFIG"

if grep -q "^\[${CRYPT_REMOTE}\]" "$CONFIG" 2>/dev/null; then
  die "Remote '$CRYPT_REMOTE' already exists in $CONFIG.
  Stopping rather than overwriting: an existing crypt remote holds existing
  backups, and replacing its key would make them unreadable."
fi

cat >>"$CONFIG" <<EOF

[$CRYPT_REMOTE]
type = crypt
remote = ${DRIVE_REMOTE}:${BACKUP_DIR}
filename_encryption = standard
directory_name_encryption = true
password = $OBSCURED_PASS
password2 = $OBSCURED_SALT
EOF

chmod "$MODE" "$CONFIG"

# Do not leave the plaintext passphrase in this process's environment.
unset PASSPHRASE SALT OBSCURED_PASS OBSCURED_SALT

printf '  wrote %s (mode %s)\n' "$CONFIG" "$MODE"

# --- 5. test the pipeline ---------------------------------------------------
say "5/5  Testing encrypt-and-upload"

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

printf 'This is a SMILE backup connectivity test. No pupil data.\n' >"$TMP/probe.txt"

if ! rclone copy "$TMP/probe.txt" "${CRYPT_REMOTE}:" --timeout 60s 2>&1; then
  die "Upload through the crypt remote failed."
fi
printf '  upload ok\n'

if ! rclone cat "${CRYPT_REMOTE}:probe.txt" >/dev/null 2>&1; then
  die "Download through the crypt remote failed."
fi
printf '  download ok\n'

# Confirm the stored object is genuinely unreadable ciphertext, not plaintext.
# If this passes silently, someone could read your backups from the Drive UI.
if rclone cat "${DRIVE_REMOTE}:${BACKUP_DIR}/probe.txt" 2>/dev/null | grep -q "connectivity test"; then
  die "The stored object is PLAINTEXT. Backups would not be encrypted.
  This happens when the crypt remote is bypassed. Check the [${CRYPT_REMOTE}]
  remote's 'remote =' line points at ${DRIVE_REMOTE}:${BACKUP_DIR}."
fi
printf '  ciphertext confirmed on Drive\n'

if rclone cryptcheck "${DRIVE_REMOTE}:${BACKUP_DIR}" "${CRYPT_REMOTE}:" 2>&1 | tail -3; then
  printf '  integrity ok\n'
else
  printf '  WARNING: cryptcheck could not verify the remote; the passphrase below is still the only copy.\n' >&2
fi

rclone deletefile "${CRYPT_REMOTE}:probe.txt" 2>/dev/null || true

# --- the one and only time the passphrase is shown -------------------------
say "PASSPHRASE — copy this now"
cat <<EOF

  Passphrase:  $PASSPHRASE
  Salt:        $SALT

  This is the ONLY time either value is displayed.

  The passphrase is stored in $CONFIG in obscured form. rclone's
  obscuring uses a static key shared across all rclone versions, so the file
  itself is protected only by its $MODE permissions and by root access to
  this host.

  LOSE THE PASSPHRASE AND EVERY BACKUP IS PERMANENTLY UNREADABLE.
  There is no reset and no recovery path.

  Write both values on the form below, seal it with the paper backup, and
  store it separately from this server.

EOF

cat <<EOF
  +--------------------------------------------------------------+
  |  SMILE backup passphrase                                      |
  |                                                              |
  |  Date sealed: .......... / .......... / 2026                   |
  |                                                              |
  |  Passphrase:                                                  |
  |  $PASSPHRASE
  |                                                              |
  |  Salt:                                                      |
  |  $SALT
  |                                                              |
  |  Drive remote:    $DRIVE_REMOTE: (token is re-issuable)           |
  |  Encrypted path:  ${DRIVE_REMOTE}:${BACKUP_DIR}                    |
  |                                                              |
  |  Custodian: ............................................      |
  +--------------------------------------------------------------+
EOF

say "Next"
cat <<EOF
  1. Seal the passphrase above. Store it apart from this server.
  2. Run the backup once and confirm it lands:
       bash backup-to-gdrive.sh
  3. Prove you can restore BEFORE you need to:
       bash restore-from-gdrive.sh --list
       bash restore-from-gdrive.sh --latest --dry-run
  4. Record the custodian and the storage location in docs/SECURITY.md.
EOF